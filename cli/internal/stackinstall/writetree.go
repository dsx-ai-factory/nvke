package stackinstall

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"
)

const overlayHeader = "# Generated by nvkectl from the site spec, the stack config and the artifact file.\n"

// WriteTree writes the stack to dir: overlays/<release>.yaml for each overlay,
// the values files the releases take, and the rendered manifests. dir must
// be empty or absent. Directories are 0700 and files 0600.
func (p *NVKEControllerStack) WriteTree(dir string) error {
	entries, err := os.ReadDir(dir)
	switch {
	case errors.Is(err, fs.ErrNotExist):
	case err != nil:
		return err
	case len(entries) > 0:
		return fmt.Errorf("%s is not empty", dir)
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	if err := os.Chmod(dir, 0o700); err != nil {
		return err
	}
	files := map[string][]byte{}
	for _, rel := range p.Releases {
		for _, path := range rel.ValuesFiles {
			data, err := fs.ReadFile(stackFS, path)
			if err != nil {
				return err
			}
			files[path] = data
		}
		if rel.Overlay == nil {
			continue
		}
		data, err := overlayYAML(rel)
		if err != nil {
			return err
		}
		files["overlays/"+rel.Name+".yaml"] = data
	}
	for _, m := range p.Manifests {
		files[m.Path] = m.Content
	}
	for path, data := range files {
		target := filepath.Join(dir, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(target), 0o700); err != nil {
			return err
		}
		if err := os.WriteFile(target, data, 0o600); err != nil {
			return err
		}
	}
	return nil
}

// overlayYAML is the overlay values file of rel.
func overlayYAML(rel Release) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(overlayHeader)
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(rel.Overlay); err != nil {
		return nil, fmt.Errorf("%s overlay: %w", rel.Name, err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("%s overlay: %w", rel.Name, err)
	}
	return b.Bytes(), nil
}
