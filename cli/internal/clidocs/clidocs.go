// Package clidocs generates the Markdown reference for a cobra command tree.
//
// The pages come from the tree the binary itself runs, never from scraped
// terminal output, so a command or flag that changes changes the reference in
// the same build. cobra's own doc package writes the body of each page; this
// package adds what that package does not emit -- aliases, deprecation
// notices, and the flag constraints cobra records as annotations -- along with
// an index and the determinism the committed output depends on.
//
// Generation builds the tree and reads its metadata. It runs no command,
// contacts no cluster or API, and needs no credential, kubeconfig or
// configured site.
package clidocs

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"
	"github.com/spf13/pflag"
)

// banner heads every generated page. An HTML comment, so GitHub renders
// nothing and the page still opens with its own title.
const banner = `> **Generated file -- do not edit.** This page is written from the nvkectl
> command tree in ` + "`cli/internal/nvkectl`" + `. To change what it says, change the
> command's own metadata -- its Short, Long, Example, Args, Aliases, deprecation
> notice or flag usage strings -- and run ` + "`make -C cli docs`" + `. An edit made here
> is lost on the next run, and ` + "`make -C cli docs-check`" + ` fails until the
> committed pages match the tree again.

`

// IndexFile is the reference's entry point, generated alongside the command
// pages. README.md so that a browser pointed at the directory opens it.
const IndexFile = "README.md"

// mdExtension matches the extension cobra's doc package links to, so a page
// this package writes is the page a cobra-generated link resolves to.
const mdExtension = ".md"

// synopsisHeading is the heading cobra puts the command's Long text under.
const synopsisHeading = "### Synopsis"

// The annotation keys cobra writes for its flag groups. cobra keeps these
// unexported (flag_groups.go), so they are restated here rather than imported.
// TestFlagGroupAnnotationKeys pins them against cobra's own public API: if an
// upgrade renames one, that test fails rather than this package silently
// dropping the section it feeds.
const (
	requiredTogetherAnnotation  = "cobra_annotation_required_if_others_set"
	oneRequiredAnnotation       = "cobra_annotation_one_required"
	mutuallyExclusiveAnnotation = "cobra_annotation_mutually_exclusive"
)

// Generate writes the reference for root into dir, replacing whatever is
// already there.
//
// The directory is emptied first, so a page for a command that no longer
// exists does not survive into the committed output. Callers that want to know
// whether anything changed compare the result against git rather than against
// the previous contents.
func Generate(root *cobra.Command, dir string) error {
	prepare(root)

	if err := emptyDir(dir); err != nil {
		return err
	}

	// The index first, while the tree is still exactly what prepare left. Each
	// renderPage below hands the command to cobra, which mutates it; writing
	// the index from the tree afterwards would describe the mutation.
	index := filepath.Join(dir, IndexFile)
	if err := os.WriteFile(index, []byte(renderIndex(root)), 0o644); err != nil { //nolint:gosec // documentation, world-readable by intent
		return fmt.Errorf("writing %s: %w", index, err)
	}

	for _, cmd := range commands(root) {
		page, err := renderPage(cmd)
		if err != nil {
			return err
		}
		name := filepath.Join(dir, pageName(cmd))
		if err := os.WriteFile(name, []byte(page), 0o644); err != nil { //nolint:gosec // documentation, world-readable by intent
			return fmt.Errorf("writing %s: %w", name, err)
		}
	}
	return nil
}

// prepare makes the tree ready to walk, and makes the pages it produces depend
// on nothing but the tree.
//
// help and completion are added lazily, by Execute rather than by the command
// constructors, so a traversal that does not run the CLI would miss both. Both
// are public commands an operator can invoke, so the reference documents them;
// and cobra links to a command's children whether or not a page was written
// for them, so missing them leaves the root page with two links that resolve
// to nothing.
func prepare(root *cobra.Command) {
	root.InitDefaultHelpCmd()
	root.InitDefaultHelpFlag()
	root.InitDefaultCompletionCmd()

	walk(root, func(c *cobra.Command) {
		// cobra stamps "Auto generated by spf13/cobra on <date>" at the foot of
		// every page unless this is set. Its doc package copies the flag down
		// from a parent only while writing a page that has a SEE ALSO section,
		// so it is set on each command here instead: one rule, no page
		// excepted.
		c.DisableAutoGenTag = true

		if c != root && c.HasSubCommands() {
			c.SetHelpCommand(hiddenHelpCommand())
		}
	})
}

// hiddenHelpCommand is the help command a group command is given before cobra
// can invent one.
//
// cobra's doc package calls InitDefaultHelpCmd on every command it renders,
// not only on the root. That adds a `help` subcommand to each group command --
// `nvkectl bootstrap help`, `nvkectl config help` -- which the binary itself does
// not have: Execute initialises help on the root alone, so `nvkectl bootstrap
// help` is an unrecognised argument that falls back to printing usage. Left
// alone, every group command's page gained a SEE ALSO link to a page for a
// command that does not exist, and the index listed eight of them.
//
// InitDefaultHelpCmd invents a command only when none is set, so setting a
// hidden one first decides which command it adds. Hidden keeps it out of the
// SEE ALSO lists, out of the index, and out of the pages, which is the state
// the real tree is in.
func hiddenHelpCommand() *cobra.Command {
	return &cobra.Command{
		Use:    "help [command]",
		Short:  "Help about any command",
		Hidden: true,
		Run:    func(_ *cobra.Command, _ []string) {},
	}
}

// commands returns every command the reference covers, parents before
// children and siblings in cobra's own order.
//
// Excluded, and the only exclusions:
//
//   - Hidden commands. A hidden command is not part of the public CLI; it is
//     excluded here for the same reason it is absent from --help.
//   - Additional help topics: a command that cannot run and has no runnable
//     children, which cobra treats as prose attached to the tree rather than
//     as a command.
//
// Deprecated commands are NOT excluded, which is where this departs from
// cobra's own IsAvailableCommand. A deprecated command still runs, so an
// operator who meets one in a script needs the reference to say what it does
// and what replaced it. renderPage gives it a deprecation notice.
func commands(root *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	walk(root, func(c *cobra.Command) { out = append(out, c) })
	return out
}

// walk calls fn on cmd and on every included descendant, depth first.
func walk(cmd *cobra.Command, fn func(*cobra.Command)) {
	fn(cmd)
	for _, child := range cmd.Commands() {
		if child.Hidden || child.IsAdditionalHelpTopicCommand() {
			continue
		}
		walk(child, fn)
	}
}

// pageName is the file a command's page is written to, matching the name
// cobra's doc package links to.
func pageName(cmd *cobra.Command) string {
	return strings.ReplaceAll(cmd.CommandPath(), " ", "_") + mdExtension
}

// renderPage returns the full Markdown page for one command.
func renderPage(cmd *cobra.Command) (string, error) {
	var buf bytes.Buffer
	// linkHandler is the identity: every page sits in one directory, so the
	// name cobra writes is already the relative link that resolves.
	if err := doc.GenMarkdownCustom(cmd, &buf, func(s string) string { return s }); err != nil {
		return "", fmt.Errorf("generating %s: %w", cmd.CommandPath(), err)
	}

	body := buf.String()
	// cobra opens every page with the heading and the short description, and
	// the extra sections belong after those and before its Synopsis. Splitting
	// on the exact prefix rather than searching for the next heading keeps this
	// honest: a command with no long description, no example and no flags has
	// no second heading to find, and a cobra release that changes the opening
	// fails here instead of silently producing a malformed page.
	prefix := "## " + cmd.CommandPath() + "\n\n" + cmd.Short + "\n\n"
	rest, ok := strings.CutPrefix(body, prefix)
	if !ok {
		return "", fmt.Errorf("generating %s: cobra's Markdown no longer starts with the heading and short description this package splices into; update clidocs to match", cmd.CommandPath())
	}

	rest, err := markdownSynopsis(cmd, rest)
	if err != nil {
		return "", err
	}

	return banner + prefix + extraSections(cmd) + rest, nil
}

// markdownSynopsis rewrites the Synopsis section cobra wrote from the
// command's Long text so that a browser renders what a terminal shows.
//
// cobra writes Long verbatim, and Long is written for a terminal, so two
// things in it do not survive GitHub Flavored Markdown. A placeholder such as
// <name> parses as an HTML tag and renders as nothing at all, turning
// "name: <name>" into "name:". An example block indented by the two spaces
// that read well in a terminal is not a code block -- Markdown wants four, or
// a fence -- so its lines are folded into the paragraph above it and the
// structure is gone.
//
// This belongs here and not in the command metadata. Long is what
// "nvkectl <command> --help" prints, so a fence or an &lt; written into it to
// satisfy Markdown is visible in the terminal, which is the interface that
// text is for. Only the Markdown rendering is wrong, so only the Markdown
// rendering is fixed.
func markdownSynopsis(cmd *cobra.Command, rest string) (string, error) {
	if cmd.Long == "" {
		return rest, nil
	}
	was := synopsisHeading + "\n\n" + cmd.Long + "\n\n"
	if !strings.Contains(rest, was) {
		return "", fmt.Errorf("generating %s: cobra no longer writes the Long text into a %q section the way clidocs rewrites it; update clidocs to match", cmd.CommandPath(), synopsisHeading)
	}
	return strings.Replace(rest, was, synopsisHeading+"\n\n"+markdownText(cmd.Long)+"\n\n", 1), nil
}

// markdownText renders terminal help text as Markdown that says the same
// thing: indented blocks become fenced code, and the prose around them has the
// characters Markdown reads as HTML escaped.
func markdownText(text string) string {
	var b strings.Builder
	lines := strings.Split(text, "\n")

	for i := 0; i < len(lines); i++ {
		block := indentedRun(lines[i:])
		if len(block) == 0 {
			b.WriteString(escapeProse(lines[i]))
			if i < len(lines)-1 {
				b.WriteString("\n")
			}
			continue
		}

		b.WriteString("```\n")
		for _, line := range dedent(block) {
			b.WriteString(line + "\n")
		}
		b.WriteString("```")
		i += len(block) - 1
		if i < len(lines)-1 {
			b.WriteString("\n")
		}
	}
	return b.String()
}

// indentedRun returns the run of indented lines at the head of lines, or nil
// when lines does not start with one.
//
// A blank line ends the run, so the examples a Long text separates with one
// become a fenced block each rather than a single block with a gap in it.
func indentedRun(lines []string) []string {
	n := 0
	for _, line := range lines {
		if strings.TrimSpace(line) == "" || (!strings.HasPrefix(line, "  ") && !strings.HasPrefix(line, "\t")) {
			break
		}
		n++
	}
	return lines[:n]
}

// dedent removes the indentation the whole block shares, which was there to
// set the block off from the prose in a terminal and is the fence's job here.
func dedent(block []string) []string {
	common := block[0][:len(block[0])-len(strings.TrimLeft(block[0], " \t"))]
	for _, line := range block[1:] {
		indent := line[:len(line)-len(strings.TrimLeft(line, " \t"))]
		for !strings.HasPrefix(indent, common) {
			common = common[:len(common)-1]
		}
	}
	out := make([]string, len(block))
	for i, line := range block {
		out[i] = line[len(common):]
	}
	return out
}

// escapeProse escapes the characters a renderer reads as something other than
// text. Without it a <placeholder> renders as nothing, and MDX -- which the
// documentation site lints these pages for -- reads a brace as the start of a
// JSX expression.
func escapeProse(line string) string {
	line = strings.ReplaceAll(line, "&", "&amp;")
	line = strings.ReplaceAll(line, "<", "&lt;")
	line = strings.ReplaceAll(line, ">", "&gt;")
	return strings.ReplaceAll(line, "{", "\\{")
}

// extraSections is what cobra's Markdown generator does not emit: the
// deprecation notice, the aliases, and the constraints cobra holds as flag
// annotations. Each is read from the command, so none of it is a second
// catalogue to maintain.
//
// Constraints a command enforces only inside RunE are invisible here, because
// cobra records nothing about them. Those belong in the command's Long text or
// in its flag usage strings, which both --help and this page already carry.
func extraSections(cmd *cobra.Command) string {
	var b strings.Builder

	if cmd.Deprecated != "" {
		fmt.Fprintf(&b, "> **Deprecated.** %s\n\n", cmd.Deprecated)
	}

	if len(cmd.Aliases) > 0 {
		b.WriteString("### Aliases\n\n")
		b.WriteString(joinCode(cmd.Aliases) + "\n\n")
	}

	if required := requiredFlags(cmd); len(required) > 0 {
		b.WriteString("### Required options\n\n")
		b.WriteString(joinCode(dashed(required)) + "\n\n")
	}

	for _, g := range flagGroups(cmd, oneRequiredAnnotation) {
		fmt.Fprintf(&b, "At least one of %s is required.\n\n", joinCode(dashed(g)))
	}
	for _, g := range flagGroups(cmd, mutuallyExclusiveAnnotation) {
		fmt.Fprintf(&b, "%s may not be used together.\n\n", joinCode(dashed(g)))
	}
	for _, g := range flagGroups(cmd, requiredTogetherAnnotation) {
		fmt.Fprintf(&b, "%s must be used together.\n\n", joinCode(dashed(g)))
	}

	return b.String()
}

// requiredFlags returns the names of the command's own flags that
// MarkFlagRequired marked, sorted.
func requiredFlags(cmd *cobra.Command) []string {
	var out []string
	cmd.NonInheritedFlags().VisitAll(func(f *pflag.Flag) {
		if f.Hidden {
			return
		}
		if values, ok := f.Annotations[cobra.BashCompOneRequiredFlag]; ok && len(values) > 0 && values[0] == "true" {
			out = append(out, f.Name)
		}
	})
	sort.Strings(out)
	return out
}

// flagGroups returns the flag groups cmd carries under annotation, each group
// as its member flag names, with the groups themselves sorted.
//
// cobra writes the same group onto each of its members, so the same group is
// read once per member and deduplicated here.
func flagGroups(cmd *cobra.Command, annotation string) [][]string {
	seen := map[string]bool{}
	var out [][]string
	cmd.Flags().VisitAll(func(f *pflag.Flag) {
		for _, group := range f.Annotations[annotation] {
			if seen[group] {
				continue
			}
			seen[group] = true
			out = append(out, strings.Split(group, " "))
		}
	})
	sort.Slice(out, func(i, j int) bool { return strings.Join(out[i], " ") < strings.Join(out[j], " ") })
	return out
}

// dashed prefixes each flag name with the two dashes an operator types.
func dashed(names []string) []string {
	out := make([]string, len(names))
	for i, n := range names {
		out[i] = "--" + n
	}
	return out
}

// joinCode renders a list as comma-separated inline code spans.
func joinCode(items []string) string {
	quoted := make([]string, len(items))
	for i, item := range items {
		quoted[i] = "`" + item + "`"
	}
	return strings.Join(quoted, ", ")
}

// emptyDir removes every Markdown file in dir, creating dir when it is absent.
//
// Removing rather than overwriting is what makes a deleted command show up: the
// page for a command that no longer exists is not rewritten, so it is simply
// gone, and the freshness check sees a deletion instead of a file nothing
// explains. Only Markdown is touched, so the directory can hold other things.
func emptyDir(dir string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("creating %s: %w", dir, err)
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("reading %s: %w", dir, err)
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), mdExtension) {
			continue
		}
		if err := os.Remove(filepath.Join(dir, e.Name())); err != nil {
			return fmt.Errorf("removing %s: %w", e.Name(), err)
		}
	}
	return nil
}
