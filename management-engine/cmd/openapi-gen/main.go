package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/getkin/kin-openapi/openapi3"

	"github.com/dsx-ai-factory/nvke/management-engine/pkg/publicapi"
	"github.com/dsx-ai-factory/nvke/management-engine/pkg/resource"
)

func main() {
	checkOnly := flag.Bool("check", false, "check generated specs without writing them")
	flag.Parse()
	if err := generate(".", *checkOnly); err != nil {
		_, _ = fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func documents(root string, surfaces []publicapi.Surface) (map[string]*openapi3.T, error) {
	published, err := kindNames(surfaces)
	if err != nil {
		return nil, err
	}
	var registrations []resource.Registration
	for _, surface := range surfaces {
		registrations = append(registrations, surface.Registrations...)
	}
	builder, err := newSchemaBuilder(root, registrations)
	if err != nil {
		return nil, err
	}
	specs := map[string]*openapi3.T{}
	for _, surface := range surfaces {
		spec, err := document(surface, builder, published)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", surface.Name, err)
		}
		specs[surface.Name] = spec
	}
	return specs, nil
}

func generate(root string, checkOnly bool) error {
	surfaces := []publicapi.Surface{publicapi.Tenant(), publicapi.Operator()}
	specs, err := documents(root, surfaces)
	if err != nil {
		return err
	}
	for _, surface := range surfaces {
		name := surface.Name
		data, err := encode(specs[name])
		if err != nil {
			return err
		}
		data = append([]byte("# SPDX-License-Identifier: Apache-2.0\n\n"+
			"# Code generated by openapi-gen. DO NOT EDIT.\n\n"+
			"# OpenAPI contract for the "+name+" API.\n\n"), data...)
		// Reload to resolve refs and validate the serialized artifact consumers receive.
		spec, err := openapi3.NewLoader().LoadFromData(data)
		if err != nil {
			return fmt.Errorf("load %s spec: %w", name, err)
		}
		if err := spec.Validate(context.Background()); err != nil {
			return fmt.Errorf("validate %s spec: %w", name, err)
		}
		path := filepath.Join(root, "api", name+".openapi.yaml")
		if checkOnly {
			existing, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(existing, data) {
				return fmt.Errorf("%s is stale, run make generate", path)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			return err
		}
	}
	return nil
}
