// The field reference presents reviewed public constraints without publishing private admission expressions.

package main

import (
	"bytes"
	"fmt"
	"html"
	"strings"

	apiextensionsv1 "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
)

// renderFields documents approved fields by operation so input restrictions stay distinct from read limits.
func renderFields(model *model) []byte {
	var out bytes.Buffer
	out.WriteString("<!-- Code generated by make generate-public-api. DO NOT EDIT. -->\n\n" +
		"# Cluster spec fields\n\n" +
		"Derived from the internal CRD and public exposure policy. Required fields apply when their parent is present. " +
		"Input restrictions apply only to the listed create/replace operations; " +
		"read projections retain their stored bounds. " +
		"The datastore also enforces CRD admission rules on the full stored object.\n\n" +
		"| Public field | Type | Operations | Required | Constraints | Description |\n" +
		"| --- | --- | --- | --- | --- | --- |\n")
	for _, field := range model.nodes {
		typeName := field.Schema.Type
		if typeName == schemaArray {
			typeName = "string[]"
		}
		// Group operations only when both their constraints and descriptions agree.
		type row struct {
			operations               []string
			constraints, description string
		}
		var rows []row
		for _, mode := range field.Access {
			schema := field.publicSchema(mode)
			constraints, description := schemaConstraints(&schema), field.publicDescription(mode)
			matched := false
			for i := range rows {
				if rows[i].constraints == constraints && rows[i].description == description {
					rows[i].operations = append(rows[i].operations, mode)
					matched = true
					break
				}
			}
			if !matched {
				rows = append(rows, row{operations: []string{mode}, constraints: constraints, description: description})
			}
		}
		for _, row := range rows {
			fmt.Fprintf(&out, "| `spec.%s` | %s | %s | %t | %s | %s |\n",
				publicPath(field.Path), typeName, strings.Join(row.operations, ", "), field.Required,
				markdownCell(row.constraints), markdownCell(row.description))
		}
	}
	return out.Bytes()
}

// schemaConstraints formats supported public bounds and patterns without exposing private admission rules.
func schemaConstraints(schema *apiextensionsv1.JSONSchemaProps) string {
	var parts []string
	for _, limit := range []struct {
		name  string
		value *int64
	}{
		{"minLength", schema.MinLength}, {"maxLength", schema.MaxLength},
		{"minItems", schema.MinItems}, {"maxItems", schema.MaxItems},
	} {
		if limit.value != nil {
			parts = append(parts, fmt.Sprintf("%s=%d", limit.name, *limit.value))
		}
	}
	if schema.Pattern != "" {
		parts = append(parts, "pattern "+markdownCode(schema.Pattern))
	}
	if schema.Items != nil && schema.Items.Schema != nil {
		if item := schemaConstraints(schema.Items.Schema); item != "" {
			parts = append(parts, "items: "+item)
		}
	}
	return strings.Join(parts, "; ")
}

// markdownCell normalizes whitespace and escapes delimiters so field prose stays within one table cell.
func markdownCell(value string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(value), " "), "|", "&#124;")
}

// markdownCode escapes schema expressions for inline code so their syntax cannot alter the reference table.
func markdownCode(value string) string {
	// Escape Markdown delimiters so schema expressions remain code in table cells.
	escaped := strings.NewReplacer("`", "&#96;", "[", "&#91;", "]", "&#93;").Replace(html.EscapeString(value))
	return "<code>" + escaped + "</code>"
}
