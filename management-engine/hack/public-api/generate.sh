# Build and compare public API artifacts so generation and drift checks share one pipeline.
set -euo pipefail

module_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
go_command=${GO:-go}
check=false
# Positional arguments keep empty invocations safe under set -u on Bash 3.2.
case "${1:-}" in
    '') set -- ;;
    --check) check=true; set -- -check ;;
    --update-lock) set -- -update-lock ;;
    *) printf 'Usage: generate.sh [--check|--update-lock]\n' >&2; exit 2 ;;
esac
cd "$module_root"
"$go_command" run ./hack/public-api "$@"
export PATH="$module_root/bin:$PATH"
generated_dir=$(mktemp -d)
trap 'rm -rf "$generated_dir"' EXIT
while IFS= read -r source; do
    mkdir -p "$generated_dir/$(dirname "$source")"
    cp "$source" "$generated_dir/$source"
done < <(find public/tenant/apis -type f \( -name '*.proto' -o -name '*.yaml' \) | sort)
# Use the same pinned module for annotation schemas, plugins and generated Go imports.
gateway_protos=$(bash hack/public-api/tools.sh --gateway-protos)
annotation_dir="$generated_dir/public/tenant/apis/protoc-gen-openapiv2/options"
mkdir -p "$annotation_dir"
cp "$gateway_protos/"*.proto "$annotation_dir/"
(
    cd "$generated_dir/public/tenant/apis"
    "$module_root/bin/buf" format --path cluster --diff --exit-code
    "$module_root/bin/buf" lint --path cluster
    "$module_root/bin/buf" generate --path cluster
    "$module_root/bin/buf" build --path cluster --as-file-descriptor-set -o "$generated_dir/descriptor.pb"
)
# Keep one complete, licensed YAML document as the handoff artifact.
openapi_dir="$generated_dir/public/tenant/gen/cluster/v1"
{
    sed 's|^//|#|' "$module_root/hack/boilerplate.go.txt"
    printf '\n# Code generated by make generate-public-api. DO NOT EDIT.\n\n'
    cat "$openapi_dir/openapi.swagger.yaml"
} >"$openapi_dir/openapi.yaml"
rm "$openapi_dir/openapi.swagger.yaml"
# grpc-gateway does not copy the proto's repository license header.
while IFS= read -r gateway_file; do
    {
        cat "$module_root/hack/boilerplate.go.txt"
        printf '\n'
        cat "$gateway_file"
    } >"$generated_dir/gateway.go"
    mv "$generated_dir/gateway.go" "$gateway_file"
done < <(find "$generated_dir/public/tenant/gen" -name '*.pb.gw.go' | sort)
# artifacts lists owned outputs so generation can compare replacements and detect stale files.
artifacts() {
    find "$1" -type f \( -name '*.pb.go' -o -name '*.pb.gw.go' -o -name 'openapi.yaml' -o -name '*.swagger.json' \) | sort
}
while IFS= read -r generated; do
    target=${generated#"$generated_dir/"}
    if "$check"; then
        if ! cmp -s "$target" "$generated"; then
            printf 'Generated artifact differs: %s; run make generate-public-api\n' "$target" >&2
            exit 1
        fi
    else
        mkdir -p "$(dirname "$target")"
        cp "$generated" "$target"
    fi
done < <(artifacts "$generated_dir/public/tenant/gen")
while IFS= read -r target; do
    if [[ ! -f "$generated_dir/$target" ]]; then
        if "$check"; then
            printf 'Stale generated artifact: %s; run make generate-public-api\n' "$target" >&2
            exit 1
        fi
        rm "$target"
    fi
done < <(artifacts public/tenant/gen)
set -- -http-descriptor "$generated_dir/descriptor.pb"
if "$check"; then set -- "$@" -check; fi
"$go_command" run ./hack/public-api "$@"
