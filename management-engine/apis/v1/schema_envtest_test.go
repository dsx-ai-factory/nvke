import (
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"
	"k8s.io/apimachinery/pkg/runtime/schema"
	k8syaml "k8s.io/apimachinery/pkg/util/yaml"
	"k8s.io/client-go/dynamic"
	"sigs.k8s.io/controller-runtime/pkg/envtest"
)

// Defaulting has to leave lifecycle present and false, because the immutability
// rule and the resolver both read it without checking for its absence.
func TestReleaseLifecycleDefaults(t *testing.T) {
	tests := []struct {
		name         string
		inputGVR     schema.GroupVersionResource
		inputYAML    string
		expectedYAML string
	}{
		{
			name:     "ClusterRelease with lifecycle omitted",
			inputGVR: GroupVersion.WithResource("clusterreleases"),
			inputYAML: `
apiVersion: internal.nvke.nvidia.com/v1
kind: ClusterRelease
metadata:
  name: cluster-release
spec:
  machineImageRef:
    name: example-image
  machineInit:
    userDataTemplate: |
      #cloud-config
`,
			expectedYAML: `
apiVersion: internal.nvke.nvidia.com/v1
kind: ClusterRelease
metadata:
  name: cluster-release
spec:
  machineImageRef:
    name: example-image
  machineInit:
    userDataTemplate: |
      #cloud-config
  lifecycle:
    deprecated: false
    hidden: false
`,
		},
		{
			name:     "NodePoolRelease with lifecycle omitted",
			inputGVR: GroupVersion.WithResource("nodepoolreleases"),
			inputYAML: `
apiVersion: internal.nvke.nvidia.com/v1
kind: NodePoolRelease
metadata:
  name: node-pool-release
spec:
  machineImageRef:
    name: example-image
  machineInit:
    userDataTemplate: |
      #cloud-config
`,
			expectedYAML: `
apiVersion: internal.nvke.nvidia.com/v1
kind: NodePoolRelease
metadata:
  name: node-pool-release
spec:
  machineImageRef:
    name: example-image
  machineInit:
    userDataTemplate: |
      #cloud-config
  lifecycle:
    deprecated: false
    hidden: false
`,
		},
	}

	const kubernetesVersion = "1.37.0"
	environment := &envtest.Environment{
		UseExistingCluster:          new(false),
		DownloadBinaryAssets:        true,
		DownloadBinaryAssetsVersion: kubernetesVersion,
		BinaryAssetsDirectory:       filepath.Join("..", "..", "bin", "envtest"),
	}
	for _, resource := range releaseResources {
		crd := loadCRD(t, resource)
		environment.CRDs = append(environment.CRDs, &crd)
	}
	config, err := environment.Start()
	t.Cleanup(func() { require.NoError(t, environment.Stop(), "stop envtest") })
	require.NoError(t, err, "start envtest")
	client, err := dynamic.NewForConfig(config)
	require.NoError(t, err, "create dynamic client")

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			inputResource := &unstructured.Unstructured{}
			require.NoError(t, k8syaml.UnmarshalStrict([]byte(tt.inputYAML), &inputResource.Object), "decode input YAML")
			expectedResource := &unstructured.Unstructured{}
			require.NoError(t, k8syaml.UnmarshalStrict([]byte(tt.expectedYAML), &expectedResource.Object), "decode expected YAML")
			resourceClient := client.Resource(tt.inputGVR)
			_, err := resourceClient.Create(t.Context(), inputResource, metav1.CreateOptions{})
			require.NoError(t, err, "create resource")

			actualResource, err := resourceClient.Get(t.Context(), inputResource.GetName(), metav1.GetOptions{})
			require.NoError(t, err, "get persisted resource")

			// Ignore only metadata generated by the API server.
			for _, field := range []string{"creationTimestamp", "generation", "managedFields", "resourceVersion", "uid"} {
				unstructured.RemoveNestedField(actualResource.Object, "metadata", field)
			}
			require.Equal(t, expectedResource.Object, actualResource.Object, "persisted resource should match expected YAML")
		})
	}
}
