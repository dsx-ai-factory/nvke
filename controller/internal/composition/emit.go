// EmitChart writes Chart.yaml: the dependency list, taken from the registry and
// ordered by name so a diff shows a real change rather than a reordering.
//
// A first-party version is written as the 0.0.0 placeholder, not the value
// `git describe` would produce right now -- the committed output has to be
// stable across commits or the regeneration check fires on every one.
func (r *Recipe) EmitChart() ([]byte, error) {
	names := make([]string, 0, len(r.Composition.Spec.ComponentRefs))
	for _, ref := range r.Composition.Spec.ComponentRefs {
		names = append(names, ref.Name)
	}
	sort.Strings(names)

	var b bytes.Buffer
	fmt.Fprintf(&b, `# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.
# SPDX-License-Identifier: Apache-2.0

# GENERATED by %s from controller/deploy/composition. Do not edit.
#
# Dependencies are pinned exactly: a composition names one tested set, so no
# floating constraints. build/nke-stack.sh stamps the first-party versions and
# repoints their repository at build time, against a copy -- this file keeps the
# canonical home and the 0.0.0 placeholders.
apiVersion: v2
name: %s
description: %s
type: application
version: "0.0.0"
appVersion: "0.0.0"
dependencies:
`, generatedBy, r.Composition.Metadata.Name, r.Composition.Metadata.Description)

	for _, name := range names {
		c := r.byName[name]
		version := c.Helm.DefaultVersion
		if version == DerivedVersion {
			version = "0.0.0"
		}
		fmt.Fprintf(&b, "  - {name: %s, version: %q, repository: %q, condition: %s.enabled}\n",
			name, version, c.Helm.DefaultRepository, name)
	}
	return b.Bytes(), nil
}

// EmitValues writes values.yaml.
//
// Component values are copied through as text rather than unmarshaled and
// re-marshaled, because their comments carry the reason each setting exists --
// which subchart key a chart actually reads, why spiffe-csi-driver is an empty
// map, why the agent's ServiceAccount name is pinned. Round-tripping through a
// Go map would drop all of it and leave a file nobody can safely edit.
func (r *Recipe) EmitValues() ([]byte, error) {
	phases, err := r.Phases()
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, `# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.
# SPDX-License-Identifier: Apache-2.0

# GENERATED by %s from controller/deploy/composition. Do not edit.
#
# INSTALL CONTRACT: Release.Namespace MUST be %q. That component's core
# templates have no namespaceOverride path, so the release namespace is pinned to
# the one name it cannot move away from and every other component carries an
# explicit override. Namespaces other than the release namespace must pre-exist:
# helm --create-namespace creates only the release namespace.

`, generatedBy, r.Composition.Spec.ReleaseNamespace)

	r.writePhases(&b, phases)
	if err := r.writeGlobals(&b); err != nil {
		return nil, err
	}
	if err := r.writeComponents(&b); err != nil {
		return nil, err
	}

	// Parse what was produced: text assembly cannot be trusted to be valid YAML.
	var check map[string]any
	if err := yaml.Unmarshal(b.Bytes(), &check); err != nil {
		return nil, fmt.Errorf("generated values.yaml is not valid YAML: %w", err)
	}
	return b.Bytes(), nil
}

func (r *Recipe) writePhases(b *bytes.Buffer, phases []Phase) {
	fmt.Fprint(b, `# Deploy phases, derived from the dependsOn edges in the composition.
#
# Helm does not order subcharts and never waits mid-release, so a single install
# races. Installing phase by phase, each with --wait, reproduces the ordering
# controller/Tiltfile gets from resource_deps. Components within a phase are
# independent and install together.
#
# Descriptive metadata: no template reads this. build/nke-stack.sh install and
# any other consumer drive the sequence from it.
phases:
`)
	for _, p := range phases {
		fmt.Fprintf(b, "  - name: %s\n    components: [%s]\n", p.Name, strings.Join(p.Components, ", "))
		for _, req := range r.requirementsBefore(p.Components) {
			if req.ProvidedBy != "" {
				fmt.Fprintf(b, "    # Not owned by this chart; supplied by %s.\n", req.ProvidedBy)
			}
			fmt.Fprint(b, "    # Checked explicitly because helm --wait only waits on workloads.\n")
			fmt.Fprint(b, "    requires:\n")
			fmt.Fprintf(b, "      - kind: %s\n        name: %s\n        namespace: %s\n        condition: %s\n",
				req.Kind, req.Name, req.Namespace, req.Condition)
		}
	}
	fmt.Fprintln(b)
}

// requirementsBefore returns the preconditions gating any component in a phase.
func (r *Recipe) requirementsBefore(components []string) []Requirement {
	in := map[string]bool{}
	for _, c := range components {
		in[c] = true
	}
	var out []Requirement
	for _, req := range r.Composition.Spec.Requires {
		if in[req.Before] {
			out = append(out, req)
		}
	}
	return out
}

func (r *Recipe) writeGlobals(b *bytes.Buffer) error {
	fmt.Fprint(b, `# Release-wide values: Helm merges `+"`global`"+` into every subchart at every
# depth, so these belong to the composition rather than to any one component.
`)
	out, err := marshalIndented(map[string]any{"global": r.Composition.Spec.Globals}, 0)
	if err != nil {
		return err
	}
	b.Write(out)
	fmt.Fprintln(b)
	return nil
}

func (r *Recipe) writeComponents(b *bytes.Buffer) error {
	for _, ref := range r.Composition.Spec.ComponentRefs {
		fmt.Fprintf(b, "# ─── %s %s\n", ref.Name, strings.Repeat("─", max(0, 68-len(ref.Name))))
		if ref.ValuesFile == "" {
			fmt.Fprintf(b, "# Enabled with no configuration.\n%s:\n  enabled: true\n\n", ref.Name)
			continue
		}
		raw, err := os.ReadFile(filepath.Join(r.Dir, ref.ValuesFile))
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%s:\n", ref.Name)
		b.Write(indentComponent(raw))
		fmt.Fprintln(b)
	}
	return nil
}

// indentComponent nests a component's values one level under its key, dropping
// the file's own SPDX and explanatory header, which describes the file rather
// than the values.
func indentComponent(raw []byte) []byte {
	lines := strings.Split(strings.TrimRight(string(raw), "\n"), "\n")

	// Skip the header: leading comments and blanks up to the first content line.
	start := 0
	for start < len(lines) {
		t := strings.TrimSpace(lines[start])
		if t != "" && !strings.HasPrefix(t, "#") {
			break
		}
		start++
	}
	// Keep any comment block immediately above that first content line.
	head := start
	for head > 0 && strings.HasPrefix(strings.TrimSpace(lines[head-1]), "#") {
		head--
	}

	var b bytes.Buffer
	for _, l := range lines[head:] {
		if strings.TrimSpace(l) == "" {
			b.WriteString("\n")
			continue
		}
		b.WriteString("  " + l + "\n")
	}
	return b.Bytes()
}

func marshalIndented(v any, _ int) ([]byte, error) {
	var b bytes.Buffer
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}
