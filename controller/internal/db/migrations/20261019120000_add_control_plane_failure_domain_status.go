package migrations

import (
	"context"
	"fmt"

	"github.com/uptrace/bun"
)

//nolint:gochecknoinits // Bun registers migrations at package initialization.
func init() {
	migrations.MustRegister(func(ctx context.Context, db *bun.DB) error {
		_, err := db.ExecContext(ctx, `ALTER TABLE nodes ADD COLUMN observed_failure_domain text NOT NULL DEFAULT '';
			ALTER TABLE clusters ADD COLUMN control_plane_failure_domains jsonb`)
		if err != nil {
			return fmt.Errorf("add control-plane failure-domain status: %w", err)
		}
		return nil
	}, func(context.Context, *bun.DB) error {
		return fmt.Errorf("down migration not supported")
	})
}
