const (
	// skipRemoveFromClusterParam is the TeardownNode workflow-outbox param key. When
	// set, teardown skips removing the node from the live Kubernetes cluster (drain,
	// kube Node deletion, etcd member removal) because the whole cluster is being torn
	// down; kubeadm reset and node-record deletion still run.
	skipRemoveFromClusterParam = "skipRemoveFromCluster"
)

// Temporal returns any workflow errors wrapped in a WorkflowExecutionError, then any further causes are wrapped in ApplicationError.
// WorkflowExecutionError and ApplicationError adds some extra information (error type and retryable status) to the message generated by
// the Error() method. This function unwraps the error stack recursively to get a nicer message without the Temporal extras.
//
// Example of what you get if you use .Error() directly on a Temporal workflow error:
// > workflow execution error (type: DeleteKubeCluster, workflowID: delete-swe-cluster-a65d540c-1dfc-4550-b8b0-9d15c82c123c, runID:
// > 89357b42-6a25-44c9-be66-108f1e56f1ef): activity error (type: swe_v1_PostgresGetCluster, scheduledEventID: 5, startedEventID: 6,
// > identity: 1@site-workflow-engine-6f87445f84-nt7h6@): postgres error (type: ResourceRetrievalError, retryable: false): failed to get
// > entity: sql: no rows in result set (type: wrapError, retryable: true): sql: no rows in result set
//
// This function will return the following for the same error:
// > postgres error: failed to get entity: sql: no rows in result set
func messageForTemporalError(err error) string {
	var weErr *temporal.WorkflowExecutionError
	if errors.As(err, &weErr) {
		cause := weErr.Unwrap()
		if cause != nil {
			return messageForTemporalError(cause)
		}

		return weErr.Error()
	}

	var appErr *temporal.ApplicationError
	if errors.As(err, &appErr) {
		// wrapError already puts the cause in the message, so we don't need to unwrap further
		if appErr.Type() == "wrapError" {
			return appErr.Message()
		}
		cause := appErr.Unwrap()
		if cause != nil {
			return appErr.Message() + ": " + messageForTemporalError(cause)
		}

		return appErr.Message()
	}

	return err.Error()
}

// startActivityHeartbeat starts a heartbeat goroutine for long running blocking activities.
// It returns a cancel function that can be used to stop the heartbeat.
// Example usage:
//
//	heartbeatCancel := startActivityHeartbeat(ctx)
//	defer heartbeatCancel()
func startActivityHeartbeat(ctx context.Context) context.CancelFunc {
	heartbeatCtx, heartbeatCancel := context.WithCancel(ctx)

	go func() {
		ticker := time.NewTicker(30 * time.Second)
		defer ticker.Stop()

		for {
			select {
			case <-heartbeatCtx.Done():
				return
			case <-ticker.C:
				activity.RecordHeartbeat(ctx)
			}
		}
	}()

	return heartbeatCancel
}

// nonRetryableIfNotFound wraps a database not found error in a non-retryable Temporal error.
// Other errors are returned unchanged.
// Example usage:
//
//	return nonRetryableIfNotFound("failed to get node", err)
func nonRetryableIfNotFound(message string, err error) error {
	if errors.Is(err, db.ErrNotFound) {
		return temporal.NewNonRetryableApplicationError(message, "db.ErrNotFound", err)
	}
	return err
}
