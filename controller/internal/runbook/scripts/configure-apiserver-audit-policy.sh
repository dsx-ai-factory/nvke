set -euo pipefail

# Default paths that can be overridden by environment variables
export KUBE_POLICY_DIR=${KUBE_POLICY_DIR:-"/etc/kubernetes/policies"}
export KUBE_POLICY_PATH=${KUBE_POLICY_PATH:-"$KUBE_POLICY_DIR/audit-policy.yaml"}
export KUBECONFIG=${KUBECONFIG:-"/etc/kubernetes/admin.conf"}
export KUBE_APISERVER_MANIFEST_PATH=${KUBE_APISERVER_MANIFEST_PATH:-"/etc/kubernetes/manifests/kube-apiserver.yaml"}
export RESTART_APISERVER_POD=${RESTART_APISERVER_POD:-"false"}

# Error handling function
error() {
    echo "Error: $1" >&2
    exit 1
}

create_audit_policy() {
  mkdir -p $KUBE_POLICY_DIR
  # Create audit policy file
  cat > $KUBE_POLICY_PATH <<EOF
# Nvidia PSOC Team K8s API Audit Policy

apiVersion: audit.k8s.io/v1
kind: Policy
omitStages:
  - "RequestReceived"
rules:
  ################ Logging Level : None ################
  # Following traffic is generated by user groups belonging to kubernetes internal traffic
  - level: None
    userGroups:
    - system:serviceaccounts:kube-system
    - system:nodes

  # Following represents system traffic generated by Kubernetes objects, low risk and high volume
  - level: None
    users:
    - system:apiserver
    - system:kube-scheduler
    - system:volume-scheduler
    - system:kube-controller-manager
    - system:node
    - system:serviceaccount:monitoring:kube-state-metrics
    - system:serviceaccount:collectorforkubernetes:collectorforkubernetes
    - system:serviceaccount:monitoring:prometheus-operator
    - system:serviceaccount:kubevirt:kubevirt-controller
    - system:serviceaccount:kubevirt:kubevirt-operator
    - system:serviceaccount:monitoring:prometheus-k8s
    - system:serviceaccount:monitoring:prometheus-adapter

  # Following are read only URL's
  - level: None
    nonResourceURLs:
    - /healthz*
    - /version
    - /swagger*

  # Following API Groups generates high volume but they are low risk events of kube-scheduler and admission-controllers
  - level: None
    resources:
    - group: "admissionregistration.k8s.io"
    - group: "cordination.k8s.io"

  # Drop the list/get/watch events
  - level: None
    verbs: ["list", "get", "watch"]
    resources:
    - resources: ["secrets", "configmaps", "limitranges", "namespaces", "nodes", "serviceaccounts", "resourcequotas", "daemonsets", "tokenreviews" , "certificatesigningrequests", "globalnetworkpolicies", "networkpolicies", "podsecuritypolicies", "clusterrolebindings", "rolebindings", "clusterroles", "roles", "virtualmachineinstances", "virtualmachines", "kubevirts"]

  ################ Logging Level : Metadata #############
  # This is most important section, where we log NGN2.0 sensitive events at Metadata level (to prevent sensitive information)
  - level: Metadata
    verbs: ["create", "update", "delete", "patch"]
    resources:
    - resources: ["secrets", "configmaps"]

  ################ Logging Level : Request ##############
  # This is extension of above section, where we log certain operations at Metadata + Request level
  - level: Request
    verbs: ["create", "update", "delete", "patch"]
    resources:
    - resources: ["limitranges", "namespaces", "nodes", "serviceaccounts", "resourcequotas", "daemonsets", "tokenreviews" , "certificatesigningrequests", "globalnetworkpolicies", "networkpolicies", "podsecuritypolicies", "clusterrolebindings", "rolebindings", "clusterroles", "roles", "virtualmachineinstances", "virtualmachines", "kubevirts"]

  # Catch-All Rule at Metadata Level
  - level: Metadata
EOF
}

restart_local_apiserver() {
    if [ "$RESTART_APISERVER_POD" != "true" ]; then
        echo "Skipping API server pod restart (RESTART_APISERVER_POD != true)"
        return
    fi

    echo "Restarting local API server pod if it exists..."
    if [ -f $KUBE_APISERVER_MANIFEST_PATH ]; then
        kubectl delete pod -n kube-system kube-apiserver-$(hostname) || true
    else
        echo "Local API server pod not found, skipping..."
    fi
    echo "Local API server pod restart triggered"
}

main() {
    create_audit_policy
    restart_local_apiserver
    echo "API Server audit logging has been configured successfully"
}


if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    main
fi
