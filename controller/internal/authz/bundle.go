package authz

// The policy bundle's file names, relative to the mounted directory. Named
// here rather than left to whoever reads them: the bundle is the deployment's
// artifact, and Local and the tests that check it all have to agree on what
// it is called.
//
// The sources under deploy/authz, read as they are written: cedar-go parses a
// multi-policy .cedar document and JSON entity lists directly, so there is no
// assembled artifact and no step between the file a person edits and the file
// the engine loads.
const (
	// policiesFile holds the rules, in native Cedar, one @id each.
	policiesFile = "policies.cedar"

	// actionsFile holds one entity per API operation, each a member of its
	// coarse group. Generated by hack/gen-authz-actions.
	actionsFile = "actions.json"

	// rolesFile holds the roles and how they nest. Hand-written.
	rolesFile = "roles.json"

	// roleMappingsFile holds the rules that grant roles to callers by what
	// their verified token says -- an OIDC claim value, a bound service
	// account, a SPIFFE path -- each for one issuer. Hand-written. Read by
	// our own Go (role_mappings.go), never by Cedar: a mapping rule is not an
	// entity.
	roleMappingsFile = "roleMappings.json"

	// schemaFile types the entities and actions. Generated by
	// hack/gen-authz-actions. Checked only by policy_validation_test.go, in
	// CI, against the checked-in bundle -- deliberately, not by Local at
	// runtime: the validator is experimental cedar-go API, and keeping it out
	// of the release binary trades away re-checking a hand-edited bundle
	// against this schema at load time. See that test file's own comment for
	// the full reasoning.
	schemaFile = "schema.json"
)

// Where the chart mounts roleMappings.json from, for the errors that tell an
// operator where a grant belongs. The chart never renders that ConfigMap; the
// operator creates it.
const (
	// defaultRoleMappingsConfigMap is the chart's default for
	// apiAuthz.roleMappingsConfigMap (_helpers.tpl); chart_bundle_sync_test.go
	// keeps the two equal.
	defaultRoleMappingsConfigMap = "nke-authz-role-mappings"

	// roleMappingsSource names that ConfigMap in an error.
	roleMappingsSource = "the ConfigMap named by the chart value apiAuthz.roleMappingsConfigMap " +
		"(" + defaultRoleMappingsConfigMap + " when empty)"
)

// entityFiles are the entity sources, in load order. Both are required: the
// generated actions and the hand-written roles are halves of one entity store,
// and either one missing leaves the mappings no roles to grant, or actions
// without groups.
var entityFiles = []string{actionsFile, rolesFile} //nolint:gochecknoglobals // a fixed table
