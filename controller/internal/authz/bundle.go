package authz

// The policy bundle's file names, relative to the mounted directory. Shared
// rather than owned by whichever engine happens to read them: the bundle is the
// deployment's artifact, and both engines, the assembler and the tests that
// check it all have to agree on what it is called.
//
// The sources under deploy/authz. deploy/authz/bundle holds the assembled form
// a cedar-agent sidecar needs, whose names are its flags' business.
const (
	// policiesFile holds the rules, in native Cedar, one @id each.
	policiesFile = "policies.cedar"

	// actionsFile holds one entity per API operation, each a member of its
	// coarse group. Generated by hack/gen-authz-actions.
	actionsFile = "actions.json"

	// rolesFile holds the roles and which subject holds which. Hand-written.
	rolesFile = "roles.json"

	// schemaFile types the entities and actions. Generated by
	// hack/gen-authz-actions. Read by the sidecar at runtime, and by the
	// bundle-validation test for both engines; see policy_validation_test.go.
	schemaFile = "schema.json"
)

// entityFiles are the entity sources, in load order. Both are required: the
// generated actions and the hand-written roles are halves of one entity store,
// and either one missing leaves principals without roles or actions without
// groups.
var entityFiles = []string{actionsFile, rolesFile} //nolint:gochecknoglobals // a fixed table
