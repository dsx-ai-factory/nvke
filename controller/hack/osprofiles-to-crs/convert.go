const (
	apiVersion = "internal.nke.nvidia.com/v1"

	specKey = "spec"

	kindMachineImage    = "MachineImage"
	kindNodePoolRelease = "NodePoolRelease"
	kindClusterRelease  = "ClusterRelease"

	osFamily = "ubuntu"

	// Annotation keys match management-engine/apis/v1.MachineInitKubernetesVersionAnnotation
	// and MachineInitKubernetesVersionInjectedAnnotation. The release spec stays
	// the boot contract; fixed-versus-injected compatibility stays metadata.
	kubernetesVersionAnnotation         = "internal.nke.nvidia.com/machine-init-kubernetes-version"
	kubernetesVersionInjectedAnnotation = "internal.nke.nvidia.com/machine-init-kubernetes-version-injected"

	syncWaveAnnotation    = "argocd.argoproj.io/sync-wave"
	syncOptionsAnnotation = "argocd.argoproj.io/sync-options"
	syncWave              = "-1"
	syncOptions           = "Prune=false"

	// defaultUbuntuVersion matches the fleet metadata index: an omitted
	// ubuntu_version means 22.04.
	defaultUbuntuVersion = "22.04"

	// fileHeader follows the fleet repository. The manifests copy proprietary
	// profile content, so they do not use the Apache-2.0 header of this module.
	fileHeader = `# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.
# SPDX-License-Identifier: LicenseRef-NvidiaProprietary
# Generated by osprofiles-to-crs. Change the profile source and regenerate.

`

	// licenseProprietary and licenseApache are the SPDX identifiers --license selects.
	// Manifests generated from the fixture profiles in this repository copy
	// data this repository owns, so they carry its Apache-2.0 header; manifests
	// generated from the fleet profiles keep the default.
	licenseProprietary = "LicenseRef-NvidiaProprietary"
	licenseApache      = "Apache-2.0"

	deprecatedNote = `# Deprecated import. Pools that already select this profile still resolve it by name.
# Upgrade-target search excludes it.

`
)

type listedProfile struct {
	name       string
	meta       utils.Metadata
	deprecated bool
}

func convert(profilesDir string) (map[string][]byte, error) {
	return convertWith(profilesDir, true)
}

// convertWith is convert with control over the Argo CD annotations. Manifests
// Argo CD installs carry a sync wave and Prune=false; manifests applied another
// way (kubectl, Tilt, envtest) have no use for them.
func convertWith(profilesDir string, gitops bool) (map[string][]byte, error) {
	if profilesDir == "" {
		return nil, errors.New("profiles directory is required")
	}
	index, err := utils.LoadOSProfileMetadata(profilesDir)
	if err != nil {
		return nil, err
	}
	listed, err := listProfiles(index)
	if err != nil {
		return nil, err
	}

	out := make(map[string][]byte, len(listed)*3)
	for _, item := range listed {
		rendered, err := renderProfile(profilesDir, item, gitops)
		if err != nil {
			return nil, err
		}
		for name, body := range rendered {
			out[name] = body
		}
	}
	return out, nil
}

func listProfiles(index *utils.MetadataIndex) ([]listedProfile, error) {
	listed := make([]listedProfile, 0, len(index.Profiles)+len(index.DeprecatedProfiles))
	for name, meta := range index.Profiles {
		listed = append(listed, listedProfile{name: name, meta: meta})
	}
	for name, meta := range index.DeprecatedProfiles {
		if _, ok := index.Profiles[name]; ok {
			return nil, fmt.Errorf("profile %q is listed in both metadata.yaml and deprecated.yaml", name)
		}
		listed = append(listed, listedProfile{name: name, meta: meta, deprecated: true})
	}
	sort.Slice(listed, func(i, j int) bool { return listed[i].name < listed[j].name })
	return listed, nil
}

func renderProfile(profilesDir string, item listedProfile, gitops bool) (map[string][]byte, error) {
	if err := validateProfile(item); err != nil {
		return nil, err
	}
	ipxe, err := readScript(profilesDir, item, "ipxeScript")
	if err != nil {
		return nil, err
	}
	userData, err := readScript(profilesDir, item, "userData.tmpl")
	if err != nil {
		return nil, err
	}
	image, err := encode(item.deprecated, machineImageDoc(item, ipxe, gitops))
	if err != nil {
		return nil, err
	}
	pool, err := encode(item.deprecated, nodePoolReleaseDoc(item, userData, gitops))
	if err != nil {
		return nil, err
	}
	cluster, err := encode(item.deprecated, clusterReleaseDoc(item, userData, gitops))
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		manifestName(item.name, kindMachineImage):    image,
		manifestName(item.name, kindNodePoolRelease): pool,
		manifestName(item.name, kindClusterRelease):  cluster,
	}, nil
}

func manifestName(profile, kind string) string {
	return profile + "-" + strings.ToLower(kind) + ".yaml"
}

func validateProfile(item listedProfile) error {
	if item.name == "" || item.name == "." || item.name == ".." || filepath.Base(item.name) != item.name {
		return fmt.Errorf("profile %q: name cannot be a path", item.name)
	}
	// The name becomes metadata.name of all three releases and the manifest
	// file name. A DNS-1123 subdomain allows dots (24.04 in a name is fine) but
	// not uppercase, underscores or more than 253 characters.
	if errs := k8svalidation.IsDNS1123Subdomain(item.name); len(errs) != 0 {
		return fmt.Errorf("profile %q: name is not a valid Kubernetes object name: %s", item.name, strings.Join(errs, "; "))
	}
	if item.meta.Architecture == "" {
		return fmt.Errorf("profile %q: architecture is required", item.name)
	}
	if _, err := time.Parse(time.DateOnly, item.meta.BuildDate); err != nil {
		return fmt.Errorf("profile %q: build_date %q must be YYYY-MM-DD", item.name, item.meta.BuildDate)
	}
	return nil
}

func readScript(profilesDir string, item listedProfile, file string) (string, error) {
	path := filepath.Join(profileDir(profilesDir, item), file)
	data, err := os.ReadFile(path)
	if err != nil {
		return "", fmt.Errorf("profile %q: read %s: %w", item.name, file, err)
	}
	if len(bytes.TrimSpace(data)) == 0 {
		return "", fmt.Errorf("profile %q: %s is empty", item.name, file)
	}
	return stripLicenseHeader(string(data)), nil
}

// profileDir is the directory holding a profile's ipxeScript and
// userData.tmpl. Deprecating a profile moves its directory into
// osProfiles/deprecated/ alongside its deprecated.yaml entry, so the active
// tree lists only what a new cluster may still select. The files have to stay
// readable either way: a cluster that already selects the profile cannot be
// provisioned or repaired without them.
func profileDir(profilesDir string, item listedProfile) string {
	if item.deprecated {
		return filepath.Join(profilesDir, "osProfiles", "deprecated", item.name)
	}
	return filepath.Join(profilesDir, "osProfiles", item.name)
}

// stripLicenseHeader drops an SPDX header after a script's first line, so a
// license header does not change the published spec.
func stripLicenseHeader(script string) string {
	lines := strings.SplitAfter(script, "\n")
	i := 1
	for i < len(lines) && strings.HasPrefix(lines[i], "# SPDX-") {
		i++
	}
	if i == 1 {
		return script
	}
	if i < len(lines) && strings.TrimSpace(lines[i]) == "" {
		i++
	}
	return lines[0] + strings.Join(lines[i:], "")
}

func machineImageDoc(item listedProfile, ipxe string, gitops bool) *enginev1.MachineImage {
	return &enginev1.MachineImage{
		TypeMeta:   metav1.TypeMeta{APIVersion: apiVersion, Kind: kindMachineImage},
		ObjectMeta: metav1.ObjectMeta{Name: item.name, Annotations: gitopsAnnotations(gitops)},
		Spec: enginev1.MachineImageSpec{
			OperatingSystem: enginev1.OperatingSystem{Family: osFamily, Version: ubuntuVersion(item.meta)},
			Architecture:    item.meta.Architecture,
			Variant:         item.meta.Variant,
			BuildDate:       item.meta.BuildDate,
			NICo:            enginev1.NICoBoot{IPXEScript: ipxe},
		},
	}
}

func nodePoolReleaseDoc(item listedProfile, userData string, gitops bool) *enginev1.NodePoolRelease {
	return &enginev1.NodePoolRelease{
		TypeMeta:   metav1.TypeMeta{APIVersion: apiVersion, Kind: kindNodePoolRelease},
		ObjectMeta: metav1.ObjectMeta{Name: item.name, Annotations: versionAnnotations(item.meta, gitops)},
		Spec: enginev1.NodePoolReleaseSpec{
			MachineImageRef: enginev1.MachineImageReference{Name: enginev1.ResourceName(item.name)},
			MachineInit:     enginev1.MachineInit{UserDataTemplate: userData},
			Lifecycle:       enginev1.ReleaseLifecycle{Deprecated: item.deprecated},
		},
	}
}

func clusterReleaseDoc(item listedProfile, userData string, gitops bool) *enginev1.ClusterRelease {
	return &enginev1.ClusterRelease{
		TypeMeta:   metav1.TypeMeta{APIVersion: apiVersion, Kind: kindClusterRelease},
		ObjectMeta: metav1.ObjectMeta{Name: item.name, Annotations: versionAnnotations(item.meta, gitops)},
		Spec: enginev1.ClusterReleaseSpec{
			MachineImageRef: enginev1.MachineImageReference{Name: enginev1.ResourceName(item.name)},
			MachineInit:     enginev1.MachineInit{UserDataTemplate: userData},
			Lifecycle:       enginev1.ReleaseLifecycle{Deprecated: item.deprecated},
		},
	}
}

func ubuntuVersion(meta utils.Metadata) string {
	if meta.UbuntuVersion == "" {
		return defaultUbuntuVersion
	}
	return meta.UbuntuVersion
}

func gitopsAnnotations(enabled bool) map[string]string {
	if !enabled {
		return map[string]string{}
	}
	return map[string]string{
		syncWaveAnnotation:    syncWave,
		syncOptionsAnnotation: syncOptions,
	}
}

func versionAnnotations(meta utils.Metadata, gitops bool) map[string]string {
	annotations := gitopsAnnotations(gitops)
	annotations[kubernetesVersionAnnotation] = meta.KubernetesVersion
	annotations[kubernetesVersionInjectedAnnotation] = strconv.FormatBool(meta.KubernetesVersionInjected)
	return annotations
}

func encode(deprecated bool, obj any) ([]byte, error) {
	root, err := manifestNode(obj)
	if err != nil {
		return nil, err
	}

	var buf bytes.Buffer
	if _, err := buf.WriteString(fileHeader); err != nil {
		return nil, err
	}
	if deprecated {
		if _, err := buf.WriteString(deprecatedNote); err != nil {
			return nil, err
		}
	}

	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(root); err != nil {
		return nil, joinClose(enc, err)
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// manifestNode renders a typed resource as a YAML node. The resource goes
// through its JSON form, so the field names are the CRD's own, and is then
// shaped for review: the conventional top-level order, no creationTimestamp,
// scripts as block scalars, and version-like strings quoted so they are never
// read back as numbers.
func manifestNode(obj any) (*yaml.Node, error) {
	data, err := json.Marshal(obj)
	if err != nil {
		return nil, fmt.Errorf("marshal manifest: %w", err)
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("render manifest: %w", err)
	}
	if doc.Kind != yaml.DocumentNode || len(doc.Content) != 1 || doc.Content[0].Kind != yaml.MappingNode {
		return nil, errors.New("render manifest: expected a mapping")
	}
	root := doc.Content[0]

	plainStyles(root)
	if metadata := child(root, "metadata"); metadata != nil {
		removeKey(metadata, "creationTimestamp")
		if annotations := child(metadata, "annotations"); annotations != nil {
			for i := 1; i < len(annotations.Content); i += 2 {
				annotations.Content[i].Style = yaml.DoubleQuotedStyle
			}
		}
	}
	for _, path := range [][]string{{specKey, "operatingSystem", "version"}, {specKey, "buildDate"}} {
		styleAt(root, path, yaml.DoubleQuotedStyle)
	}
	for _, path := range [][]string{{specKey, "nico", "ipxeScript"}, {specKey, "machineInit", "userDataTemplate"}} {
		styleAt(root, path, yaml.LiteralStyle)
	}
	orderKeys(root, "apiVersion", "kind", "metadata", specKey)
	return root, nil
}

// plainStyles clears the flow and double-quoted styles that JSON input brings,
// so mappings render in block form and the encoder picks each scalar's style.
func plainStyles(node *yaml.Node) {
	node.Style = 0
	for _, c := range node.Content {
		plainStyles(c)
	}
}

func child(node *yaml.Node, key string) *yaml.Node {
	for i := 0; i+1 < len(node.Content); i += 2 {
		if node.Content[i].Value == key {
			return node.Content[i+1]
		}
	}
	return nil
}

func removeKey(node *yaml.Node, key string) {
	for i := 0; i+1 < len(node.Content); i += 2 {
		if node.Content[i].Value == key {
			node.Content = append(node.Content[:i], node.Content[i+2:]...)
			return
		}
	}
}

func styleAt(node *yaml.Node, path []string, style yaml.Style) {
	for _, key := range path {
		if node = child(node, key); node == nil {
			return
		}
	}
	node.Style = style
}

// orderKeys moves the listed keys to the front of a mapping, in that order, and
// drops every other top-level key (a typed resource's status is never published).
func orderKeys(node *yaml.Node, keys ...string) {
	ordered := make([]*yaml.Node, 0, len(keys)*2)
	for _, key := range keys {
		for i := 0; i+1 < len(node.Content); i += 2 {
			if node.Content[i].Value == key {
				ordered = append(ordered, node.Content[i], node.Content[i+1])
				break
			}
		}
	}
	node.Content = ordered
}

func joinClose(enc *yaml.Encoder, err error) error {
	if closeErr := enc.Close(); closeErr != nil {
		return errors.Join(err, closeErr)
	}
	return err
}

func publish(outputDir string, docs map[string][]byte, check bool) error {
	if outputDir == "" {
		return errors.New("output directory is required")
	}
	if err := guardPublishedSpecs(outputDir, docs); err != nil {
		return err
	}
	if check {
		return checkOutput(outputDir, docs)
	}
	if err := os.MkdirAll(outputDir, 0o755); err != nil {
		return fmt.Errorf("create output directory: %w", err)
	}
	for _, name := range sortedKeys(docs) {
		path := filepath.Join(outputDir, name)
		// Generated manifests are review artifacts, not secrets.
		if err := os.WriteFile(path, docs[name], 0o644); err != nil { //nolint:gosec // G306: reviewable YAML is world-readable.
			return fmt.Errorf("write %s: %w", path, err)
		}
	}
	return nil
}

func guardPublishedSpecs(outputDir string, docs map[string][]byte) error {
	for _, name := range sortedKeys(docs) {
		previous, err := os.ReadFile(filepath.Join(outputDir, name))
		if err != nil {
			if os.IsNotExist(err) {
				continue
			}
			return fmt.Errorf("read %s: %w", name, err)
		}
		changed, err := immutableChanged(previous, docs[name])
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		if changed {
			return fmt.Errorf("%s: regeneration would change a published spec; publish a new profile name instead", name)
		}
	}
	return nil
}

type publishedManifest struct {
	Kind     string `yaml:"kind"`
	Metadata struct {
		Name        string            `yaml:"name"`
		Annotations map[string]string `yaml:"annotations"`
	} `yaml:"metadata"`
	Spec map[string]any `yaml:"spec"`
}

func immutableChanged(previous, next []byte) (bool, error) {
	var left, right publishedManifest
	if err := yaml.Unmarshal(previous, &left); err != nil {
		return false, fmt.Errorf("parse published manifest: %w", err)
	}
	if err := yaml.Unmarshal(next, &right); err != nil {
		return false, fmt.Errorf("parse generated manifest: %w", err)
	}
	if left.Kind != right.Kind || left.Metadata.Name != right.Metadata.Name {
		return true, nil
	}
	delete(left.Spec, "lifecycle")
	delete(right.Spec, "lifecycle")
	if !reflect.DeepEqual(left.Spec, right.Spec) {
		return true, nil
	}
	return annotation(left, kubernetesVersionAnnotation) != annotation(right, kubernetesVersionAnnotation) ||
		annotation(left, kubernetesVersionInjectedAnnotation) != annotation(right, kubernetesVersionInjectedAnnotation), nil
}

func annotation(manifest publishedManifest, key string) string {
	if manifest.Metadata.Annotations == nil {
		return ""
	}
	return manifest.Metadata.Annotations[key]
}

func checkOutput(outputDir string, docs map[string][]byte) error {
	var problems []string
	for _, name := range sortedKeys(docs) {
		body, err := os.ReadFile(filepath.Join(outputDir, name))
		if err != nil {
			problems = append(problems, name+": missing")
			continue
		}
		if !bytes.Equal(body, docs[name]) {
			problems = append(problems, name+": differs")
		}
	}
	entries, err := os.ReadDir(outputDir)
	if err != nil {
		return fmt.Errorf("read output directory: %w", err)
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".yaml") {
			continue
		}
		if _, ok := docs[entry.Name()]; !ok {
			problems = append(problems, entry.Name()+": not generated from the profile source")
		}
	}
	if len(problems) > 0 {
		return fmt.Errorf("generated manifests drifted:\n%s", strings.Join(problems, "\n"))
	}
	return nil
}

func sortedKeys(docs map[string][]byte) []string {
	names := make([]string, 0, len(docs))
	for name := range docs {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

// relicense rewrites the SPDX identifier in the header of every document.
func relicense(docs map[string][]byte, license string) error {
	switch license {
	case licenseProprietary:
		return nil
	case licenseApache:
	default:
		return fmt.Errorf("unsupported license %q: use %s or %s", license, licenseProprietary, licenseApache)
	}
	from := []byte("SPDX-License-Identifier: " + licenseProprietary)
	to := []byte("SPDX-License-Identifier: " + license)
	for name, body := range docs {
		docs[name] = bytes.Replace(body, from, to, 1)
	}
	return nil
}
